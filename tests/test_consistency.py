"""Tests of behavior which is consistent across related processes."""

import numpy as np
import pytest

import samplepaths
from samplepaths import (
    BesselProcess,
    BrownianBridge,
    BrownianExcursion,
    BrownianMeander,
    BrownianMotion,
    CauchyProcess,
    ColoredNoise,
    DiffusionProcess,
    FractionalBrownianMotion,
    FractionalGaussianNoise,
    GaussianNoise,
    GeometricBrownianMotion,
    InverseGaussianProcess,
    SquaredBesselProcess,
    WienerProcess,
)


@pytest.mark.parametrize("method", ["sample", "sample_davies_harte", "sample_hosking"])
@pytest.mark.parametrize("hurst", [0.3, 0.5, 0.7])
def test_fractional_brownian_motion_methods_return_the_motion(
    method: str,
    hurst: float,
) -> None:
    n = 16
    motion = getattr(
        FractionalBrownianMotion(hurst=hurst, t=2.0, rng=np.random.default_rng(4)),
        method,
    )(n)

    # Every sampling method returns the motion, which starts at zero and is
    # the cumulative sum of the noise generated by the same method.
    noise_method = "sample_davies_harte" if method == "sample" else method
    noise = getattr(
        FractionalGaussianNoise(hurst=hurst, t=2.0, rng=np.random.default_rng(4)),
        noise_method,
    )(n)

    assert motion.shape == (n + 1,)
    assert motion[0] == 0.0
    np.testing.assert_allclose(motion[1:], np.cumsum(noise))


@pytest.mark.parametrize(
    "process_type",
    [
        BesselProcess,
        BrownianBridge,
        BrownianExcursion,
        BrownianMeander,
        CauchyProcess,
        SquaredBesselProcess,
        WienerProcess,
    ],
)
def test_processes_built_on_brownian_motion_have_no_drift_or_scale(
    process_type: type,
) -> None:
    instance = process_type()

    # Drift and scale are parameters of BrownianMotion only.
    assert not hasattr(instance, "drift")
    assert not hasattr(instance, "scale")
    assert not isinstance(instance, BrownianMotion)


def test_geometric_brownian_motion_has_no_scale() -> None:
    instance = GeometricBrownianMotion(drift=0.1, volatility=0.2)

    assert instance.drift == 0.1
    assert not hasattr(instance, "scale")
    assert not isinstance(instance, BrownianMotion)


def test_diffusion_volatility_exponent_is_a_function_of_time() -> None:
    received: list[float] = []

    def volexp(t: float) -> float:
        received.append(t)
        return 0.0

    n = 8
    instance = DiffusionProcess(volexp=volexp, t=2.0, rng=np.random.default_rng(1))
    instance.sample(n)

    np.testing.assert_allclose(received, np.linspace(0, 2.0, n + 1)[1:])


def test_inverse_gaussian_process_mean_change_after_sampling() -> None:
    instance = InverseGaussianProcess(mean=lambda t: t, rng=np.random.default_rng(5))
    instance.sample(50)

    def mean(t: float) -> float:
        return 10 * t

    instance.mean = mean
    instance.rng = np.random.default_rng(9)
    samples = instance.sample(50)

    fresh = InverseGaussianProcess(mean=mean, rng=np.random.default_rng(9))
    np.testing.assert_array_equal(samples, fresh.sample(50))


@pytest.mark.parametrize("t", [0.5, 1.0, 4.0])
@pytest.mark.parametrize("beta", [-2, -1, 0, 1, 2])
def test_colored_noise_scales_with_the_interval(beta: float, t: float) -> None:
    n = 256
    paths = 400

    colored = ColoredNoise(beta=beta, t=t, rng=np.random.default_rng(3)).sample_paths(n, paths)
    gaussian = GaussianNoise(t=t, rng=np.random.default_rng(3)).sample_paths(n, paths)

    # A realization has the variance of Gaussian noise on the same interval,
    # t / n, and a zero mean.
    np.testing.assert_allclose(colored.var(), t / n, rtol=0.02)
    np.testing.assert_allclose(gaussian.var(), t / n, rtol=0.02)
    np.testing.assert_allclose(colored.mean(axis=1), 0.0, atol=1e-12)


def test_colored_noise_sample_and_sample_paths_scale_alike() -> None:
    single = ColoredNoise(beta=1, t=4.0, rng=np.random.default_rng(3)).sample(512)
    unit = ColoredNoise(beta=1, t=1.0, rng=np.random.default_rng(3)).sample(512)

    np.testing.assert_allclose(single, 2.0 * unit)


@pytest.mark.parametrize("name", ["ColoredNoise", "WhiteNoise", "PinkNoise"])
def test_colored_noise_needs_two_increments(name: str) -> None:
    instance = getattr(samplepaths, name)()

    with pytest.raises(ValueError):
        instance.sample(1)

    assert instance.sample(2).shape == (2,)
